package main

import "fmt"

// NumMatrix - структура, хранящая матрицу для последующих запросов суммы.
type NumMatrix struct {
	matrix [][]int
}

// Constructor создаёт объект NumMatrix по заданной матрице matrix.
func Constructor(matrix [][]int) NumMatrix {
	return NumMatrix{matrix: matrix}
}

// SumRegion возвращает сумму элементов матрицы внутри прямоугольника
// с верхним левым углом (row1, col1) и нижним правым углом (row2, col2).
func (nm *NumMatrix) SumRegion(row1, col1, row2, col2 int) int {
	/*
		TASK: Дана неизменяемая матрица и множество запросов на сумму элементов
		внутри прямоугольника, заданного верхним левым углом (row1, col1)
		и нижним правым углом (row2, col2). Нужно для каждого запроса вернуть
		сумму элементов этого прямоугольника.

		METHOD: Bruteforce (перебор элементов прямоугольника)
		Предобработка не выполняется: матрица просто сохраняется в объекте.
		Для каждого запроса перебираем все строки от row1 до row2 и все столбцы
		от col1 до col2 и складываем элементы, попадающие в прямоугольник.

		TIME COMPLEXITY: O(1) на создание объекта,
		O((row2 - row1 + 1) * (col2 - col1 + 1)) на запрос.
		- Запрос обращается к каждому элементу прямоугольника ровно один раз.
		- В худшем случае прямоугольник совпадает со всей матрицей,
		  поэтому запрос занимает O(m * n).

		SPACE COMPLEXITY: O(1) дополнительной памяти.
		- Копий матрицы не создаём, элементы перебираются на месте.
		- Сумма накапливается в одной переменной int.
	*/
	sum := 0

	// Проходим по строкам прямоугольника от row1 до row2 включительно.
	for i := row1; i <= row2; i++ {
		// Проходим по столбцам прямоугольника от col1 до col2 включительно.
		for j := col1; j <= col2; j++ {
			sum += nm.matrix[i][j]
		}
	}

	return sum
}

func main() {
	// Пример 1 из условия задачи.
	matrix := [][]int{
		{3, 0, 1, 4, 2},
		{5, 6, 3, 2, 1},
		{1, 2, 0, 1, 5},
		{4, 1, 0, 1, 7},
		{1, 0, 3, 0, 5},
	}

	nm := Constructor(matrix)
	fmt.Println(nm.SumRegion(2, 1, 4, 3)) // 8
	fmt.Println(nm.SumRegion(1, 1, 2, 2)) // 11
	fmt.Println(nm.SumRegion(1, 2, 2, 4)) // 12

	// Пример 2 из условия задачи.
	nm2 := Constructor([][]int{
		{1, 2, 3},
		{4, 5, 6},
		{7, 8, 9},
	})
	fmt.Println(nm2.SumRegion(0, 0, 1, 1)) // 12
	fmt.Println(nm2.SumRegion(1, 1, 2, 2)) // 28
}
