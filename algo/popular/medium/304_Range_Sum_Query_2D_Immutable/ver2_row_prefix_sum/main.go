package main

import "fmt"

// NumMatrixV2 - структура, хранящая префиксные суммы каждой строки матрицы.
type NumMatrixV2 struct {
	// prefix[i][j] - сумма элементов строки i от столбца 0 до столбца j - 1.
	// Размер по второму измерению на 1 больше, чем число столбцов матрицы,
	// чтобы prefix[i][0] всегда была равна 0.
	prefix [][]int
}

// ConstructorV2 создаёт объект NumMatrixV2 и строит префиксные суммы строк.
func ConstructorV2(matrix [][]int) NumMatrixV2 {
	nm := NumMatrixV2{prefix: make([][]int, len(matrix))}

	for i, row := range matrix {
		// Нулевой элемент строки - сумма пустого префикса.
		nm.prefix[i] = make([]int, len(row)+1)
		for j, value := range row {
			// К сумме предыдущего префикса прибавляем текущий элемент.
			nm.prefix[i][j+1] = nm.prefix[i][j] + value
		}
	}

	return nm
}

// SumRegionV2 возвращает сумму элементов матрицы внутри прямоугольника
// с верхним левым углом (row1, col1) и нижним правым углом (row2, col2).
func (nm *NumMatrixV2) SumRegionV2(row1, col1, row2, col2 int) int {
	/*
		TASK: Дана неизменяемая матрица и множество запросов на сумму элементов
		внутри прямоугольника, заданного верхним левым углом (row1, col1)
		и нижним правым углом (row2, col2). Нужно для каждого запроса вернуть
		сумму элементов этого прямоугольника.

		METHOD: Row prefix sums (префиксные суммы по строкам)
		В отличие от полного перебора здесь выполняется предобработка: для каждой
		строки один раз считаются суммы всех её префиксов, то есть
		prefix[i][j] = сумма элементов строки i от столбца 0 до столбца j - 1.

		Благодаря этому сумму отрезка одной строки можно получить за O(1):
		это разность prefix[i][col2 + 1] - prefix[i][col1], так как
		вычитание убирает из суммы все элементы левее прямоугольника.

		Сумма прямоугольника получается сложением таких отрезков построчно,
		поэтому запрос всё ещё зависит от числа строк прямоугольника,
		но уже не зависит от числа столбцов.

		TIME COMPLEXITY: O(m * n) на создание объекта, O(row2 - row1 + 1) на запрос.
		- При построении каждая ячейка таблицы вычисляется за O(1).
		- Запрос проходит только по строкам прямоугольника и для каждой строки
		  выполняет одно вычитание, поэтому время запроса не зависит от ширины.

		SPACE COMPLEXITY: O(m * n).
		- Таблица префиксных сумм содержит m * (n + 1) элементов.
		- Дополнительная память на сам запрос не выделяется.
	*/
	sum := 0

	// Складываем сумму нужного отрезка каждой строки прямоугольника.
	for i := row1; i <= row2; i++ {
		sum += nm.prefix[i][col2+1] - nm.prefix[i][col1]
	}

	return sum
}

func main() {
	// Пример 1 из условия задачи.
	matrix := [][]int{
		{3, 0, 1, 4, 2},
		{5, 6, 3, 2, 1},
		{1, 2, 0, 1, 5},
		{4, 1, 0, 1, 7},
		{1, 0, 3, 0, 5},
	}

	nm := ConstructorV2(matrix)
	fmt.Println(nm.SumRegionV2(2, 1, 4, 3)) // 8
	fmt.Println(nm.SumRegionV2(1, 1, 2, 2)) // 11
	fmt.Println(nm.SumRegionV2(1, 2, 2, 4)) // 12

	// Пример 2 из условия задачи.
	nm2 := ConstructorV2([][]int{
		{1, 2, 3},
		{4, 5, 6},
		{7, 8, 9},
	})
	fmt.Println(nm2.SumRegionV2(0, 0, 1, 1)) // 12
	fmt.Println(nm2.SumRegionV2(1, 1, 2, 2)) // 28
}
