package main

import "fmt"

// NumMatrixV3 - структура, хранящая двумерные префиксные суммы матрицы.
type NumMatrixV3 struct {
	// prefix[i][j] - сумма всех элементов матрицы в подматрице
	// [0..i-1] x [0..j-1], то есть всех элементов выше i - 1 и левее j - 1.
	// Таблица на 1 больше матрицы по обоим измерениям, нулевая строка и
	// нулевой столбец означают сумму пустой подматрицы и равны 0.
	prefix [][]int
}

// ConstructorV3 создаёт объект NumMatrixV3 и строит двумерные префиксные суммы.
func ConstructorV3(matrix [][]int) NumMatrixV3 {
	m := len(matrix)
	n := len(matrix[0])

	prefix := make([][]int, m+1)
	for i := range prefix {
		prefix[i] = make([]int, n+1)
	}

	// Заполняем таблицу по строкам сверху вниз.
	for i := range m {
		for j := range n {
			// К текущему элементу прибавляем суммы всех элементов выше и левее,
			// а их пересечение вычитаем, чтобы не учесть его дважды.
			prefix[i+1][j+1] = matrix[i][j] + prefix[i][j+1] + prefix[i+1][j] - prefix[i][j]
		}
	}

	return NumMatrixV3{prefix: prefix}
}

// SumRegionV3 возвращает сумму элементов матрицы внутри прямоугольника
// с верхним левым углом (row1, col1) и нижним правым углом (row2, col2).
func (nm *NumMatrixV3) SumRegionV3(row1, col1, row2, col2 int) int {
	/*
		TASK: Дана неизменяемая матрица и множество запросов на сумму элементов
		внутри прямоугольника, заданного верхним левым углом (row1, col1)
		и нижним правым углом (row2, col2). Нужно для каждого запроса вернуть
		сумму элементов этого прямоугольника за O(1) времени.

		METHOD: 2D prefix sums (двумерные префиксные суммы)
		В отличие от префиксов по строкам здесь предобработка учитывает
		и строки, и столбцы сразу: prefix[i][j] хранит сумму всех элементов
		подматрицы [0..i-1] x [0..j-1].

		Сумма прямоугольника получается формулой включений-исключений
		из четырёх элементов таблицы:

		prefix[row2+1][col2+1] - prefix[row1][col2+1]
		- prefix[row2+1][col1] + prefix[row1][col1]

		Первое слагаемое содержит всю нужную область и всё лишнее: часть выше
		строки row1, часть левее столбца col1 и их пересечение. Вычитая верхнюю
		и левую части, а пересечение, вычтое дважды, прибавляем обратно,
		в итоге остаётся ровно сумма запрошенного прямоугольника.

		Лишние нулевая строка и нулевой столбец избавляют от проверок границ:
		запрос из первой строки или первого столбца считается той же формулой.

		TIME COMPLEXITY: O(m * n) на создание объекта, O(1) на каждый запрос.
		- При построении каждая ячейка таблицы вычисляется за O(1).
		- Запрос выполняет фиксированное число обращений к таблице (4 сложения
		  и вычитания) и не зависит ни от размеров матрицы, ни от размеров
		  прямоугольника. Таблица строится один раз, поэтому все последующие
		  запросы к ней только читаются.

		SPACE COMPLEXITY: O(m * n).
		- Таблица префиксных сумм содержит (m + 1) * (n + 1) элементов.
		- Копий матрицы не храним, дополнительная память на запрос не нужна.
	*/
	return nm.prefix[row2+1][col2+1] - nm.prefix[row1][col2+1] -
		nm.prefix[row2+1][col1] + nm.prefix[row1][col1]
}

func main() {
	// Пример 1 из условия задачи.
	matrix := [][]int{
		{3, 0, 1, 4, 2},
		{5, 6, 3, 2, 1},
		{1, 2, 0, 1, 5},
		{4, 1, 0, 1, 7},
		{1, 0, 3, 0, 5},
	}

	nm := ConstructorV3(matrix)
	fmt.Println(nm.SumRegionV3(2, 1, 4, 3)) // 8
	fmt.Println(nm.SumRegionV3(1, 1, 2, 2)) // 11
	fmt.Println(nm.SumRegionV3(1, 2, 2, 4)) // 12

	// Пример 2 из условия задачи.
	nm2 := ConstructorV3([][]int{
		{1, 2, 3},
		{4, 5, 6},
		{7, 8, 9},
	})
	fmt.Println(nm2.SumRegionV3(0, 0, 1, 1)) // 12
	fmt.Println(nm2.SumRegionV3(1, 1, 2, 2)) // 28
}
