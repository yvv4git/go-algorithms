package main

func findLength(nums1 []int, nums2 []int) int {
	/*
		TASK: Даны два целочисленных массива nums1 и nums2. Нужно вернуть
		максимальную длину подмассива, который встречается в обоих массивах.

		METHOD: Bruteforce (полный перебор)
		Перебираем все пары стартовых позиций (i, j) в nums1 и nums2.
		Для каждой пары сравниваем nums1[i+k] и nums2[j+k], пока элементы
		совпадают, и запоминаем максимальную длину такого совпадения.

		TIME COMPLEXITY: O(n * m * min(n, m))
		- Существует n * m пар стартовых позиций.
		- Для каждой пары сравнение идёт не дольше min(n-i, m-j) <= min(n, m).
		- В худшем случае (все элементы равны) получаем O(n * m * min(n, m)).

		SPACE COMPLEXITY: O(1)
		- Дополнительные массивы не создаются.
		- Хранятся только текущая длина совпадения и максимум.
	*/
	best := 0

	for i := range nums1 {
		for j := range nums2 {
			k := 0
			// Сравниваем элементы, пока они совпадают и не вышли за границы.
			for i+k < len(nums1) && j+k < len(nums2) && nums1[i+k] == nums2[j+k] {
				k++
			}
			if k > best {
				best = k
			}
		}
	}

	return best
}
