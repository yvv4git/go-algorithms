package main

func maxCoinsV2(nums []int) int {
	/*
		TASK: Дано n шаров с числами nums. Лопаем все шары по одному.
		При лопании i-го шара получаем coins = nums[i-1] * nums[i] * nums[i+1],
		где выходящие за границы соседи считаются равными 1.
		Найти максимальную сумму очков.

		METHOD: Dynamic Programming (interval DP)
		Ключевая идея: решаем задачу в обратном порядке. Вместо того чтобы выбирать,
		какой шар лопнуть первым, выбираем, какой шар лопнуть ПОСЛЕДНИМ.

		Если на отрезке (left, right) последним лопнуть шар k, то к моменту его
		лопания все шары между left и k, а также между k и right уже лопнуты.
		Значит соседи шара k - это строго nums[left] и nums[right].

		Добавим в массив по единице с обоих концов (виртуальные шары), чтобы
		единообразно обрабатывать края.

		TIME COMPLEXITY: O(n^3)
		- Три вложенных цикла: по длине подотрезка len, по началу left и по k.
		- Каждый подотрезок обрабатывается за O(1) операций.

		SPACE COMPLEXITY: O(n^2)
		- Таблица dp размера (n+2) x (n+2).
	*/
	// Добавляем виртуальные шары с 1 по краям, чтобы не обрабатывать границы отдельно.
	// Например, nums = [3,1,5,8] превращается в points = [1,3,1,5,8,1].
	points := make([]int, 0, len(nums)+2)
	points = append(points, 1)
	points = append(points, nums...)
	points = append(points, 1)

	n := len(points)
	// dp[left][right] - максимальное число очков, которое можно получить,
	// лопая все шары строго между left и right (сами left и right не лопаются).
	dp := make([][]int, n)
	for i := range dp {
		dp[i] = make([]int, n)
	}

	// Перебираем длину подотрезка, начиная с самого короткого (0 шаров).
	// Так мы гарантируем, что подотрезки меньшей длины уже посчитаны.
	for length := 2; length < n; length++ {
		// left - левая граница, right - правая граница.
		// Между ними ровно length-1 шаров.
		for left := 0; left+length < n; left++ {
			right := left + length

			// Пробуем лопнуть шар k последним на этом подотрезке.
			// Соседи шара k в момент его лопания - это points[left] и points[right],
			// потому что все шары между ними уже лопнуты.
			for k := left + 1; k < right; k++ {
				coins := dp[left][k] + points[left]*points[k]*points[right] + dp[k][right]
				if coins > dp[left][right] {
					dp[left][right] = coins
				}
			}
		}
	}

	// Ответ - максимальные очки на всём исходном массиве шаров,
	// то есть строго между виртуальными единицами points[0] и points[n-1].
	return dp[0][n-1]
}
