package main

func maxCoins(nums []int) int {
	/*
		TASK: Дано n шаров с числами nums. Лопаем все шары по одному.
		При лопании i-го шара получаем coins = nums[i-1] * nums[i] * nums[i+1],
		где выходящие за границы соседи считаются равными 1.
		Найти максимальную сумму очков.

		METHOD: Bruteforce (полный перебор)
		Перебираем все порядки лопания шаров (все перестановки порядка).
		Для каждого порядка считаем получаемые очки и запоминаем максимум.

		Рекурсивная функция bruteforce получает текущий массив оставшихся шаров
		и накопленную сумму очков. На каждом шаге выбираем шар, который лопнем
		следующим, удаляем его из массива и рекурсивно продолжаем.

		TIME COMPLEXITY: O(n!)
		- На первом уровне n вариантов выбора шара, на втором n-1, и так далее.
		- Итого n! перестановок, каждая обрабатывается за O(1) (после удаления шара).

		SPACE COMPLEXITY: O(n)
		- Глубина рекурсии равна количеству шаров n.
		- На каждом уровне создаётся копия массива размером до n,
		  суммарно по пути рекурсии это O(n) дополнительной памяти.
	*/
	var best int
	bruteforce(nums, 0, &best)
	return best
}

// bruteforce перебирает все порядки лопания шаров и обновляет *best.
//
// Параметры:
//   nums  - массив оставшихся нелопнутых шаров.
//   coins - сумма очков, накопленная на уже лопнутых шарах.
//   best  - указатель на текущий максимум очков.
//
// Базовый случай: когда массив пуст, все шары лопнуты.
// Сравниваем накопленную сумму с текущим максимумом и сохраняем большую.
//
// Рекурсивный случай: пробуем лопнуть каждый из оставшихся шаров.
// Соседи берутся из текущего массива: шар слева и шар справа.
// Если шар на краю массива, отсутствующий сосед считается равным 1.
// Затем удаляем лопнувший шар из массива и вызываемся рекурсивно.
func bruteforce(nums []int, coins int, best *int) {
	// Базовый случай: все шары лопнуты, обновляем максимум.
	if len(nums) == 0 {
		if coins > *best {
			*best = coins
		}
		return
	}

	// Перебираем каждый шар как кандидата на лопание следующим.
	for i := range nums {
		// Определяем соседей: слева и справа от текущего шара.
		// Если соседа нет (шар на краю массива), берём 1.
		left, right := 1, 1
		if i-1 >= 0 {
			left = nums[i-1]
		}
		if i+1 < len(nums) {
			right = nums[i+1]
		}

		// Создаём новый массив без лопнутого шара.
		// Например: nums = [3,1,5], i = 1 (шар 1),
		// тогда next = [3,5].
		next := make([]int, 0, len(nums)-1)
		next = append(next, nums[:i]...)
		next = append(next, nums[i+1:]...)

		// Рекурсивно продолжаем с оставшимися шарами,
		// добавляя очки за лопнувший шар: left * nums[i] * right.
		bruteforce(next, coins+left*nums[i]*right, best)
	}
}
