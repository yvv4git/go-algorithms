package main

import (
	"bufio"
	"fmt"
	"os"
)

// correctWithHamming - единственная функция, которую вызывает main.
//
// ============================ ЧТО ДАНО И ЧТО НАДО ============================
//
// Есть исходная строка s, состоящая только из символов '0' и '1' (это данные).
// Её надо передать по каналу, в котором может испортиться ровно один бит.
// То есть один символ '0' может стать '1', или наоборот.
// Ноль ошибок тоже допустим.
//
// Программа запускается дважды.
//
// При mode == 1 выполняется кодирование.
// На вход приходит исходная строка s (данные).
// На выходе получается более длинная строка с контрольными битами.
//
// При mode == 2 выполняется декодирование.
// На вход приходит строка s, которую получили из канала, возможно с одним испорченным битом.
// На выходе получается восстановленная исходная строка.
//
// Важно: параметр s - это разная строка в зависимости от mode.
//
// При mode == 1 значение s - это данные до кодирования.
// При mode == 2 значение s - это закодированная строка после канала.
//
// Поэтому внутри функции s передаётся в разные помощники: hammingEncode или hammingDecode.
// Других параметров у функции нет.
//
// ========================= КАК УСТРОЕН КОД ХЭММИНГА ==========================
//
// Идея: кроме битов данных в строку добавляют контрольные биты.
// Контрольный бит - это просто бит чётности.
// Он хранит, чётное или нечётное количество единиц в своей группе позиций.
//
// Все позиции строки нумеруются с 1, а не с 0.
// Позиции с номерами 1, 2, 4, 8, 16, ... (степени двойки) являются контрольными.
// Все остальные позиции (3, 5, 6, 7, 9, ...) являются данными, туда кладут символы s.
//
// Пример расположения для 4 битов данных (n = 4):
//
//	позиция:   1     2     3     4     5     6     7
//	что там:  c1    c2    d1    c4    d2    d3    d4
//	          ^     ^           ^
//	          контрольные       контрольный
//	          биты              бит
//
//	d1..d4 - биты данных (символы исходной строки s по порядку).
//	c1, c2, c4 - контрольные биты.
//
// Каждый контрольный бит отвечает за свою группу позиций.
// Номер группы j - это номер бита в двоичной записи номера позиции.
//
// Контрольный бит c1 (позиция 1 = 2^0) проверяет позиции, у которых 0-й бит номера равен 1.
// Это позиции 1, 3, 5, 7, 9, ...
//
// Контрольный бит c2 (позиция 2 = 2^1) проверяет позиции, у которых 1-й бит номера равен 1.
// Это позиции 2, 3, 6, 7, 10, 11, ...
//
// Контрольный бит c4 (позиция 4 = 2^2) проверяет позиции, у которых 2-й бит номера равен 1.
// Это позиции 4, 5, 6, 7, 12, 13, ...
//
// Вот та же схема через двоичные номера позиций.
// Звёздочка означает, что позиция входит в группу этого контрольного бита.
//
//	позиция  двоичный  c1  c2  c4
//	   1       001      *   .   .
//	   2       010      .   *   .
//	   3       011      *   *   .
//	   4       100      .   .   *
//	   5       101      *   .   *
//	   6       110      .   *   *
//	   7       111      *   *   *
//
// Правило простое: позиция входит в группу j, если j-й бит её номера равен 1.
//
// ============================ ПРИМЕР КОДИРОВАНИЯ =============================
//
// mode = 1, s = "1010" (n = 4 бита данных).
//
// Шаг 1. Выбираем число контрольных битов r.
// Нужно минимальное r, для которого 2^r >= n + r + 1.
// Для n = 4 подходит r = 3, потому что 2^3 = 8 >= 4+3+1 = 8.
// Длина результата равна n + r = 7.
//
// Шаг 2. Раскладываем данные d1..d4 по неконтрольным позициям по порядку.
//
//	s[0]='1' -> позиция 3
//	s[1]='0' -> позиция 5
//	s[2]='1' -> позиция 6
//	s[3]='0' -> позиция 7
//
// Пока строка выглядит так (в контрольных позициях пока пусто):
//
//	позиция:  1  2  3  4  5  6  7
//	бит:      ?  ?  1  ?  0  1  0
//
// Шаг 3. Считаем контрольные биты.
// XOR - это сумма по модулю 2, то есть чётность: 1, если единиц нечётное число.
// c1 = XOR битов на позициях 1,3,5,7.
// Позиция 1 - сам c1, её не берём, остаётся 3,5,7: 1 XOR 0 XOR 0 = 1, значит c1 = 1.
// c2 = XOR битов на позициях 2,3,6,7.
// Позиция 2 - сам c2, не берём, остаётся 3,6,7: 1 XOR 1 XOR 0 = 0, значит c2 = 0.
// c4 = XOR битов на позициях 4,5,6,7.
// Позиция 4 - сам c4, не берём, остаётся 5,6,7: 0 XOR 1 XOR 0 = 1, значит c4 = 1.
//
// Шаг 4. Записываем контрольные биты на свои места.
//
//	позиция:  1  2  3  4  5  6  7
//	бит:      1  0  1  1  0  1  0
//
// Результат: "1011010".
// Это и вернёт функция при mode = 1.
//
// =========================== ПРИМЕР ДЕКОДИРОВАНИЯ ============================
//
// mode = 2, s = "1011110" (в канале испортился ровно один бит).
// Сравним с правильной строкой "1011010": отличается только позиция 5.
//
// Шаг 1. По длине строки 7 восстанавливаем r.
// Нужно 2^r >= 7 + 1 = 8, значит r = 3.
// Плюс единица здесь потому, что есть ещё случай "ошибки нет", которому соответствует нулевой синдром.
//
// Шаг 2. Для каждой группы j считаем XOR всех её позиций.
// Теперь контрольные биты тоже входят в проверку, они ведь уже записаны.
// j = 0, позиции 1,3,5,7: 1 XOR 1 XOR 1 XOR 0 = 1, значит бит 0 синдрома = 1.
// j = 1, позиции 2,3,6,7: 0 XOR 1 XOR 1 XOR 0 = 0, значит бит 1 синдрома = 0.
// j = 2, позиции 4,5,6,7: 1 XOR 1 XOR 1 XOR 0 = 1, значит бит 2 синдрома = 1.
//
// Шаг 3. Собираем синдром из этих битов: бит j ставится на место 2^j.
// Синдром равен 1*1 + 0*2 + 1*4 = 5.
//
// Шаг 4. Синдром не равен 0, значит ошибка есть, и её номер равен синдрому.
// Испорчена позиция 5, поэтому инвертируем её: '1' -> '0'.
//
//	Позиция:  1  2  3  4  5  6  7
//	было:     1  0  1  1  1  1  0
//	стало:    1  0  1  1  0  1  0
//
// Шаг 5. Выбрасываем контрольные позиции 1,2,4, оставляем 3,5,6,7.
// Получаем '1','0','1','0', то есть "1010".
// Это исходная строка.
//
// =========================== ПОЧЕМУ СИНДРОМ РАБОТАЕТ =========================
//
// Номер позиции pos в двоичном виде говорит, в каких группах она участвует.
// Если перевернуть бит в позиции pos, то испортятся ровно те проверки, чьи номера j являются единичными битами числа pos.
// Собранный из этих проверок синдром - это и есть двоичная запись числа pos.
// Например, позиция 5 = 101 в двоичном виде, она входит в группы j=0 и j=2.
// Поэтому синдром получился 101, то есть 5.
// Если синдром равен 0, ошибки нет, и мы ничего не исправляем.
//
// ============================= КРАЙНИЕ СЛУЧАИ =================================
//
//	s == ""  -> возвращается "" (и при кодировании, и при декодировании);
//	s == "0" -> при mode = 1 получается "000" (r = 2, длина 3).
//	mode не 1 и не 2 -> возвращается "".
//
// Если ошибок две и больше, условие задачи нарушено, и правильный ответ не гарантируется.
// Код Хэмминга исправляет только одну ошибку.
//
// ============================== СЛОЖНОСТЬ ====================================
//
// TIME COMPLEXITY: O(n log n).
// Кодирование и декодирование перебирают O(n) позиций для каждого из r = O(log n) контрольных битов.
//
// SPACE COMPLEXITY: O(n).
// Новая строка имеет длину n + r, где r = O(log n), то есть O(n).
func correctWithHamming(mode int, s string) string {
	switch mode {
	case 1:
		return hammingEncode(s)
	case 2:
		return hammingDecode(s)
	default:
		return ""
	}
}

// hammingParityBits возвращает минимальное число контрольных битов r, которого хватает для n битов данных.
//
// Условие: 2^r >= n + r + 1.
//
//	n + r   - всего позиций в закодированной строке;
//	+ 1     - ещё нужен "нулевой" синдром, означающий "ошибки нет".
//
// У каждой одиночной ошибки должен быть свой уникальный ненулевой номер.
// Поэтому различных синдромов (2^r) должно хватать на все позиции плюс ноль.
//
// Примеры: n = 1 -> r = 2; n = 4 -> r = 3; n = 11 -> r = 4.
func hammingParityBits(n int) int {
	if n == 0 {
		return 0
	}
	r := 1
	for (1 << r) < n+r+1 {
		r++
	}
	return r
}

// isPowerOfTwo сообщает, является ли номер позиции степенью двойки.
// То есть является ли эта позиция контрольной (1, 2, 4, 8, ...).
//
// Трюк x&(x-1): у степени двойки в двоичном виде ровно одна единица.
// Поэтому побитовое И с (x-1) даёт 0.
// Например: 4 = 100, 3 = 011, 100&011 = 0.
func isPowerOfTwo(x int) bool {
	return x > 0 && x&(x-1) == 0
}

// hammingEncode кодирует строку данных data (это параметр s при mode = 1).
//
// Возвращает строку encoded длины n + r, где:
//
//	n - длина data;
//	r - число контрольных битов из hammingParityBits.
//
// Шаги те же, что разобраны в примере выше.
// 1. Создать пустую строку encoded на n + r позиций.
// 2. Разложить data по неконтрольным позициям по порядку.
// 3. Посчитать каждый контрольный бит как XOR данных в своей группе и записать его на позицию 2^j.
func hammingEncode(data string) string {
	n := len(data)
	if n == 0 {
		return ""
	}

	r := hammingParityBits(n)
	total := n + r
	encoded := make([]byte, total)

	// Шаг 1: раскладываем данные по позициям 1..total.
	// Позиции с номерами-степенями двойки пропускаем, они для контрольных битов.
	dataIndex := 0
	for pos := 1; pos <= total; pos++ {
		if !isPowerOfTwo(pos) {
			encoded[pos-1] = data[dataIndex]
			dataIndex++
		}
	}

	// Шаг 2: считаем контрольные биты.
	// j - номер группы.
	// Контрольный бит группы j стоит на позиции 2^j, то есть в срезе Go на индексе (1<<j)-1.
	for j := 0; j < r; j++ {
		parity := 0
		for pos := 1; pos <= total; pos++ {
			// Сами контрольные позиции при подсчёте пропускаем, потому что их значения ещё не посчитаны.
			// Учитываем только позиции с данными.
			if isPowerOfTwo(pos) {
				continue
			}
			// Проверяем j-й бит номера позиции: (pos>>j)&1.
			// Если он равен 1, позиция входит в группу j.
			if (pos>>j)&1 == 1 {
				parity ^= int(encoded[pos-1] - '0') // XOR символа '0'/'1' как числа 0/1
			}
		}
		encoded[(1<<j)-1] = byte(parity) + '0' // обратно в символ '0'/'1'
	}
	return string(encoded)
}

// hammingDecode декодирует принятую строку received (это параметр s при mode = 2).
// Функция исправляет не более одной ошибки.
//
// Возвращает строку данных без контрольных битов (исходную строку).
//
// Шаги:
// 1. По длине total восстановить число контрольных битов r.
// 2. Для каждой группы j посчитать XOR всех позиций группы, включая контрольные, и сложить синдром.
// 3. Если синдром не равен 0, инвертировать бит на позиции, равной синдрому.
// 4. Выбросить контрольные позиции и вернуть оставшиеся биты.
func hammingDecode(received string) string {
	total := len(received)
	if total == 0 {
		return ""
	}

	// Восстанавливаем r из длины строки: минимальное r с 2^r >= total + 1.
	// +1 снова для случая "ошибки нет" (нулевой синдром).
	r := 0
	for (1 << r) < total+1 {
		r++
	}

	bits := []byte(received)
	syndrome := 0
	for j := 0; j < r; j++ {
		parity := 0
		for pos := 1; pos <= total; pos++ {
			// Здесь, в отличие от кодирования, контрольные позиции не пропускаем.
			// При проверке они должны участвовать наравне со всеми.
			if (pos>>j)&1 == 1 {
				parity ^= int(bits[pos-1] - '0')
			}
		}
		// Если XOR группы равен 1, значит в этой группе нечётное число единиц.
		// Фиксируем j-й бит синдрома.
		if parity == 1 {
			syndrome |= 1 << j
		}
	}

	// Ненулевой синдром - это номер испорченной позиции (1..total).
	// Инвертируем этот бит.
	// Если синдром равен 0, ошибки нет, и ничего не делаем.
	if syndrome >= 1 && syndrome <= total {
		if bits[syndrome-1] == '0' {
			bits[syndrome-1] = '1'
		} else {
			bits[syndrome-1] = '0'
		}
	}

	// Выбрасываем контрольные позиции (1, 2, 4, 8, ...), остальное - данные.
	decoded := make([]byte, 0, total-r)
	for pos := 1; pos <= total; pos++ {
		if !isPowerOfTwo(pos) {
			decoded = append(decoded, bits[pos-1])
		}
	}
	return string(decoded)
}

// main читает со стандартного входа два значения: mode и s.
// Формат ввода: "1 1010" (кодировать) или "2 1011110" (декодировать).
// Печатает результат correctWithHamming(mode, s).
func main() {
	reader := bufio.NewReader(os.Stdin)
	writer := bufio.NewWriter(os.Stdout)
	defer writer.Flush()

	var mode int
	var s string
	if _, err := fmt.Fscan(reader, &mode, &s); err != nil {
		return
	}

	fmt.Fprintln(writer, correctWithHamming(mode, s))
}
