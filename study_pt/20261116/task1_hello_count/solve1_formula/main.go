package main

import (
	"bufio"
	"fmt"
	"os"
)

func countGreetings(a, b int64) int64 {
	/*
		TASK: Посчитать, сколько раз за день произнесено слово "Hello!" в опенспейсе.
		Интроверт - это сотрудник, который сам не здоровается первым, а отвечает на приветствие.
		Экстраверт - это сотрудник, который здоровается со всеми, кто уже внутри, и все ему отвечают.
		Каждый обмен приветствиями даёт ровно два слова: один говорит, второй отвечает.
		Пример: a = 1 интроверт и b = 2 экстраверта дают ответ 6.
		Пары "интроверт и экстраверт" - 2, каждая даёт 2 привета, получается 4.
		Пара "два экстраверта" - 1, она даёт 2 привета, получается 2.
		Всего 4 + 2 = 6, как в первом примере задачи.
		Случаи по b: b = 0 - экстравертов нет, ответ 0 при любом a; b = 1 - один экстраверт, ответ 2*a.
		Граница: a = 0, b = 0 - в опенспейсе никого нет, ответ 0.
		Граница: a = 0, b = 2 - только два экстраверта, они обмениваются двумя приветами, ответ 2.
		Если a = 5, b = 0, интроверты друг друга не приветствуют, ответ 0.
		Отрицательные a или b не встречаются по условию задачи.

		METHOD: Formula (замкнутая формула)
		Порядок входа не важен, потому что каждая подходящая пара сотрудников обменивается двумя приветствиями ровно один раз за день.
		Пара "интроверт и экстраверт" встречается, когда второй из них входит, а первый уже внутри.
		Таких пар a*b, потому что каждого интроверта можно соединить с каждым экстравертом.
		Пара "два экстраверта" встречается, когда второй экстраверт входит, а первый уже внутри.
		Таких пар b*(b-1)/2 - это число сочетаний из b по 2.
		Пар "два интроверта" нет, интроверты не начинают разговор.
		Каждая пара даёт ровно 2 привета, поэтому ответ равен 2*a*b + b*(b-1).

		TIME COMPLEXITY: O(1)
		Формула состоит из нескольких арифметических операций, циклов нет.

		SPACE COMPLEXITY: O(1)
		Дополнительная память не нужна, используются только переменные a, b и результат.
	*/
	return 2*a*b + b*(b-1)
}

func main() {
	reader := bufio.NewReader(os.Stdin)
	writer := bufio.NewWriter(os.Stdout)
	defer writer.Flush()

	var a, b int64
	if _, err := fmt.Fscan(reader, &a, &b); err != nil {
		return
	}

	fmt.Fprintln(writer, countGreetings(a, b))
}
