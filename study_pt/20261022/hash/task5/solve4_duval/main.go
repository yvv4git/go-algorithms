package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func maxSubstringV4(s string) string {
	/*
		TASK: Найти лексикографически максимальную непрерывную подстроку строки S.
		Подстрока - это непрерывный кусок строки.
		Лексикографический порядок - это порядок как в словаре: символы сравниваются слева направо, и больше та строка, у которой на первом различии символ больше.
		Если одна строка является префиксом другой, то более длинная строка больше.
		Пример: S = "abacaba", максимальная подстрока "caba".
		Пример: S = "babb", максимальная подстрока "bb", потому что "bb" длиннее "b" и имеет "b" префиксом.
		Пример: S = "abc", максимальная подстрока "c", потому что "c" больше "bc" и "abc".
		Граница: S = "a", ответ "a"; S = "az", ответ "z".
		Пустая строка недопустима по условию, но для S = "" функция возвращает "".
		Контрпример: S = "ab", максимальная подстрока "b", а не "ab", потому что на первом различии "b" > "a".
		Функция возвращает саму максимальную подстроку, а не её позицию.

		METHOD: Duval (алгоритм Дюваля)
		Суффикс S[i:] - это конец строки начиная с позиции i.
		Максимальная подстрока всегда является суффиксом, поэтому ищем максимальный суффикс.
		Алгоритм Дюваля сравнивает двух кандидатов i и j и хранит длину k их совпавшего префикса.
		Сравниваем символы s[i+k] и s[j+k]:
		- если они равны, увеличиваем k;
		- если s[i+k] < s[j+k], кандидат i проигрывает, поэтому сдвигаем i за совпавший блок: i = max(i+k+1, j);
		- если s[i+k] > s[j+k], кандидат j проигрывает, поэтому сдвигаем j за совпавший блок: j = j+k+1.
		После сдвига k обнуляется, потому что новый кандидат сравнивается заново.
		Когда j+k выходит за конец строки, все кандидаты просмотрены, и i указывает на начало максимального суффикса.
		Возвращаем s[i:].

		TIME COMPLEXITY: O(n)
		- Указатели i и j двигаются только вперёд, каждый символ участвует в сравнении ограниченное число раз.

		SPACE COMPLEXITY: O(1)
		- Храним только три индекса i, j, k.
	*/
	n := len(s)
	if n == 0 {
		return ""
	}

	i, j, k := 0, 1, 0
	for j+k < n {
		switch {
		case s[i+k] == s[j+k]:
			k++
		case s[i+k] < s[j+k]:
			i = max(i+k+1, j)
			j = i + 1
			k = 0
		default:
			j = j + k + 1
			k = 0
		}
	}

	return s[i:]
}

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	scanner.Buffer(make([]byte, 1024*1024), 1024*1024)
	scanner.Scan()
	s := strings.TrimSpace(scanner.Text())

	fmt.Println(maxSubstringV4(s))
}
