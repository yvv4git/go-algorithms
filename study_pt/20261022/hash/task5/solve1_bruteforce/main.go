package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func maxSubstring(s string) string {
	/*
		TASK: Найти лексикографически максимальную непрерывную подстроку строки S.
		Подстрока - это непрерывный кусок строки.
		Лексикографический порядок - это порядок как в словаре: символы сравниваются слева направо, и больше та строка, у которой на первом различии символ больше.
		Если одна строка является префиксом другой, то более длинная строка больше.
		Пример: S = "abacaba", максимальная подстрока "caba", потому что она начинается с "c" и является самым длинным суффиксом с "c".
		Пример: S = "babb", максимальная подстрока "bb", потому что "bb" длиннее "b" и имеет "b" префиксом.
		Пример: S = "abc", максимальная подстрока "c", потому что "c" больше "bc" и "abc".
		Граница: S = "a", ответ "a"; S = "az", ответ "z".
		Пустая строка недопустима по условию, но для S = "" функция возвращает "".
		Контрпример: S = "ab", максимальная подстрока "b", а не "ab", потому что на первом различии "b" > "a".
		Функция возвращает саму максимальную подстроку, а не её позицию.

		METHOD: Bruteforce (перебор суффиксов)
		Суффикс S[i:] - это конец строки начиная с позиции i.
		Максимальная подстрока всегда является суффиксом: если подстрока S[i..j] не доходит до конца строки, то S[i..j+1] длиннее и имеет её своим префиксом, значит она больше.
		Поэтому достаточно найти лексикографически максимальный суффикс.
		Заводим best - индекс текущего лучшего суффикса, начинаем с best = 0.
		Перебираем i от 1 до n-1 и сравниваем s[i:] с s[best:] встроенным сравнением строк.
		Если s[i:] больше, обновляем best = i.
		В конце возвращаем s[best:].

		TIME COMPLEXITY: O(n^2)
		- Перебираем n суффиксов, сравнение двух суффиксов в худшем случае занимает O(n).

		SPACE COMPLEXITY: O(1)
		- Дополнительная память не зависит от n, храним только индексы.
	*/

	n := len(s)
	if n == 0 {
		return ""
	}

	best := 0
	for i := 1; i < n; i++ {
		if s[i:] > s[best:] {
			best = i
		}
	}

	return s[best:]
}

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	scanner.Buffer(make([]byte, 1024*1024), 1024*1024)
	scanner.Scan()
	s := strings.TrimSpace(scanner.Text())

	fmt.Println(maxSubstring(s))
}
